import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../deploy/telegram-worker/worker.js', import.meta.url), 'utf8');
const { default: worker } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const env = { TELEGRAM_BOT_TOKEN: 'test-token', TELEGRAM_RELAY_SECRET: 'relay-secret', TELEGRAM_WEBHOOK_SECRET: 'webhook-secret', TELEGRAM_SITE_URL: 'https://site.example' };
let forwarded = [];
globalThis.fetch = async (url, options) => { forwarded.push({url, options}); return Response.json({ok:true}); };
const call = (path, body, header = 'X-Relay-Secret', secret = 'relay-secret') => worker.fetch(new Request('https://worker.example' + path, {method:'POST', headers: {[header]:secret}, body:typeof body === 'string' ? body : JSON.stringify(body)}), env);
assert.equal((await call('/api', {method:'getMe', payload:{}}, 'X-Relay-Secret', 'wrong')).status, 403);
assert.equal(forwarded.length, 0);
assert.equal((await call('/api', {method:'getMe', payload:{}})).status, 200);
assert.equal(forwarded[0].url, 'https://api.telegram.org/bottest-token/getMe');
assert.equal((await call('/api', {method:'deleteWebhook', payload:{}})).status, 400);
assert.equal((await call('/api', '{')).status, 400);
assert.equal((await call('/api', 'x'.repeat(65537))).status, 413);
assert.equal((await call('/webhook', {update_id:1}, 'X-Telegram-Bot-Api-Secret-Token', 'webhook-secret')).status, 200);
assert.equal(forwarded[1].url, 'https://site.example/api/telegram-webhook.php');
assert.equal(forwarded[1].options.headers['X-Telegram-Bot-Api-Secret-Token'], 'webhook-secret');
assert.equal(forwarded[1].options.redirect, 'manual');
assert.equal((await call('/missing', {})).status, 404);
globalThis.fetch = async () => new Response('', {status:302, headers:{Location:'https://other.example'}});
assert.equal((await call('/api', {method:'getMe', payload:{}})).status, 502);
globalThis.fetch = async () => { throw new Error('network unavailable'); };
assert.equal((await call('/api', {method:'getMe', payload:{}})).status, 502);
console.log('PASS: Worker authentication, API allowlist, payload limits, fixed webhook destination, redirect rejection and network failure');
